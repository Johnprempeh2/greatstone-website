// Writes netlify/database/seed/compose-problems.sql from src/data/compose-problems.mjs (GRE-3407), so the database
// copy of the ComposeExplorer mapping follows the editable source. `--check` exits 1 when the file is stale.
// The seed replaces both tables in one transaction; run it against the site database after editing the source.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { problems } from '../src/data/compose-problems.mjs';

export const SEED_PATH = fileURLToPath(new URL('../netlify/database/seed/compose-problems.sql', import.meta.url));
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

export function buildSeed(list = problems) {
  const rows = list.map((p, i) => `  (${q(p.id)}, ${q(p.title)}, ${q(p.subline || '')}, ${q(p.source || '')}, ${p.placeholder ? 'true' : 'false'}, ${i})`);
  const links = list.flatMap((p) => p.services.map((slug, i) => `  (${q(p.id)}, ${q(slug)}, ${i})`));
  return [
    '-- Generated by scripts/gen-compose-seed.mjs from src/data/compose-problems.mjs. Do not edit by hand.',
    'BEGIN;',
    'DELETE FROM public.compose_problem_services;',
    'DELETE FROM public.compose_problems;',
    'INSERT INTO public.compose_problems (id, title, subline, source, placeholder, sort) VALUES',
    rows.join(',\n') + ';',
    'INSERT INTO public.compose_problem_services (problem_id, service_slug, sort) VALUES',
    links.join(',\n') + ';',
    'COMMIT;',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = buildSeed();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(SEED_PATH, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== sql) { console.error('compose seed is stale: run node scripts/gen-compose-seed.mjs'); process.exit(1); }
  } else {
    writeFileSync(SEED_PATH, sql);
    console.log('wrote ' + SEED_PATH);
  }
}
